create table if not exists public.airline (
  airline_icao char(3) primary key,
  name text null,
  iata char(2) null
);

create table if not exists public.position_source (
  position_source_id smallint generated by default as identity primary key,
  position_source_val text null
);

create table if not exists public.squawk (
  squawk_id char(4) primary key,
  squawk_val text null
);

create table if not exists public.category (
  category_id serial primary key,
  category_val text null
);

create table if not exists public.aircraft (
  aircraft_icao24 char(6) primary key,
  origin_country text null
);

