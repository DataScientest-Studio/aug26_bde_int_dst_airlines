/* to be discussed; if changed, fix in: public.airport */
create table if not exists public.timezone (
  timezone_id serial primary key,
  name text unique not null
);

create table if not exists public.airport (
  airport_icao varchar(4) primary key,
  name text,
  iata varchar(3),
  city text,
  latitude numeric(9,6),
  longitude numeric(9,6),
  timezone int4 references timezone(timezone_id),
  lamin numeric(9,6),
  lamax numeric(9,6),
  lomin numeric(9,6),
  lomax numeric(9,6)
);

create table if not exists public.icon (
  icon_id serial primary key,
  icon text
);

create table if not exists public.weather (
  weather_id serial primary key,
  icon_id int4 references icon(icon_id),
  main text,
  description text
);

create table if not exists public.status(
  status_id serial primary key,
  value text
);

